/**
 * 「题材」维度。
 *
 * 为什么需要它：
 *   过去整条流水线只有一套"企业/宏观调研"的骨架（产业链、资本、政策、分歧地图…），
 *   于是问一个娱乐人物，模型会硬把它套进宏观经济模板，最后产出"日本旅游业分析"这种
 *   跟题目毫无关系的东西。题材维度就是用来在拆题阶段就换掉整套"作战纲领"的。
 *
 * 每个题材有两条可编辑模板（在「提示词管理 → 题材纲领」里改）：
 *   genre.<key>.plan   作战纲领：拆题原则 / 分析视角 / 信得过的来源 / 写作要诀
 *                       —— 注入到「拆解」「视角」「来源评估」三个步骤
 *   genre.<key>.voice  语境与取信标准（2~3 行）
 *                       —— 注入到系统底座 system.base，替换掉原来写死的"中国宏观统计口径"
 *
 * 运行时永远从数据库读模板（render.js），这里只是出厂默认值。
 */

