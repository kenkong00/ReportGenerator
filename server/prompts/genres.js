export const GENRE_TEMPLATE_CATEGORY = 'genre'

export function allGenreTemplateDefaults() {
  const out = []
  let ord = 500
  for (const key of GENRE_DETECTABLE) {
    out.push({
      key: `genre.${key}.plan`,
      name: `题材纲领 · ${GENRES[key].label}`,
      category: GENRE_TEMPLATE_CATEGORY,
      stageKey: null,
      description: `「${GENRES[key].label}」题材的拆题原则 / 分析视角 / 信得过的来源 / 写作要诀。会注入到「拆解」「视角」「来源评估」三步。想让这类题更接地气或更专业，改这里。`,
      variables: [],
      template: GENRE_PLANS[key],
      ord: ord++
    })
    out.push({
      key: `genre.${key}.voice`,
      name: `题材语境 · ${GENRES[key].label}`,
      category: GENRE_TEMPLATE_CATEGORY,
      stageKey: null,
      description: `「${GENRES[key].label}」题材的语境与取信标准，注入到系统底座（每次调用都生效）。`,
      variables: [],
      template: GENRE_VOICES[key],
      ord: ord++
    })
  }
  out.push({
    key: 'genre.generic.voice',
    name: '题材语境 · 通用兜底',
    category: GENRE_TEMPLATE_CATEGORY,
    stageKey: null,
    description: '题材没识别出来或选了「自动识别」但判断失败时使用的取信标准。',
    variables: [],
    template: GENERIC_VOICE,
    ord: ord++
  })
  return out
}
