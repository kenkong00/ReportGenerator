export const GENRE_KEYS = Object.keys(GENRES)

/** 可以被自动识别出来的题材（不含 auto） */
export const GENRE_DETECTABLE = ['life', 'ent', 'society', 'biz', 'tech']

/** 识别不出来时的兜底题材 */
export const FALLBACK_GENRE = 'life'

export function genreLabel(key) {
  return GENRES[key]?.label || '通用'
}

/** 把任意输入规范成合法题材键 */
export function normalizeGenre(key) {
  const k = String(key || '').trim()
  if (k === 'auto') return 'auto'
  if (GENRE_DETECTABLE.includes(k)) return k
  return 'auto'
}

