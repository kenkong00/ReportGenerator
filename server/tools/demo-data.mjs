function realSources() {
  const a = readJson('search-raw.json', { results: [] }).results || []
  const b = readJson('search-raw2.json', { results: [] }).results || []
  const map = new Map()
  for (const r of [...a, ...b]) {
    if (JUNK.test(r.domain)) continue
    if ((r.title || '').length < 6) continue
    if (!map.has(r.url)) map.set(r.url, r)
  }
  return [...map.values()].sort((x, y) => (y.quality || 0) - (x.quality || 0))
}

